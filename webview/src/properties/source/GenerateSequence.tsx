import React from 'react';
import { InfoTooltip } from '../../components/InfoTooltip';

/**
 * GenerateSequence Properties Component
 * 
 * Author: Mike Nimer <mikenimer@google.com>
 * 
 * Purpose:
 * This component provides a property configuration panel for the GenerateSequence streaming source node.
 * It allows developers to configure bounded or unbounded sequence generation, rate limiting, maximum read time,
 * and custom code generation instructions for Apache Beam pipelines in both Java and Python.
 * 
 * Architectural Decisions:
 * - Supports both 'bounded' (start to stop) and 'unbounded' (infinite streaming from start) modes.
 * - Supports rate limiting with elements-per-period and period duration (in seconds).
 * - Integrates interactive InfoTooltip components next to all field labels.
 * - Follows the 8pt grid system for spacing and consistent dark theme styling.
 * - Emits state changes to parent via the standard onChange callback.
 */

export interface GenerateSequencePropertiesData {
  sequenceMode?: 'bounded' | 'unbounded';
  start?: number | string;
  stop?: number | string;
  withRateLimit?: boolean;
  elementsPerPeriod?: number | string;
  periodSeconds?: number | string;
  maxReadTimeSeconds?: number | string;
  system_instructions?: string;
  special_instructions?: string;
}

export interface GenerateSequenceNode {
  data: {
    label: string;
    beam_transform?: string;
    system_instructions?: string;
    special_instructions?: string;
    properties?: GenerateSequencePropertiesData;
  };
}

interface GenerateSequencePropertiesProps {
  node: GenerateSequenceNode;
  onChange: (properties: any) => void;
}

/**
 * GenerateSequenceProperties Component
 * 
 * Renders form fields for configuring Beam GenerateSequence transform.
 */
export const GenerateSequenceProperties: React.FC<GenerateSequencePropertiesProps> = ({ node, onChange }) => {
  // Extract existing properties with sensible defaults
  const properties = node.data.properties || {};
  const sequenceMode = properties.sequenceMode || 'unbounded';
  const start = properties.start ?? 0;
  const stop = properties.stop ?? 10;
  const withRateLimit = properties.withRateLimit ?? false;
  const elementsPerPeriod = properties.elementsPerPeriod ?? 1;
  const periodSeconds = properties.periodSeconds ?? 1;
  const maxReadTimeSeconds = properties.maxReadTimeSeconds ?? '';
  const systemInstructions =
    node.data.system_instructions ??
    node.data.special_instructions ??
    properties.system_instructions ??
    properties.special_instructions ??
    '';

  /**
   * Handles updating property fields when inputs change.
   */
  const handleChange = (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement>) => {
    const { name, value, type } = e.target;
    const isCheckbox = type === 'checkbox';
    const checked = isCheckbox ? (e.target as HTMLInputElement).checked : undefined;

    // Build updated properties
    const updated = {
      ...properties,
      [name]: isCheckbox ? checked : value
    };

    // If switching to bounded and stop is not set, initialize default stop
    if (name === 'sequenceMode') {
      if (value === 'bounded' && (updated.stop === undefined || updated.stop === '')) {
        updated.stop = 10;
      }
    }

    onChange(updated);
  };

  return (
    <div className="flex flex-col gap-4">
      {/* Sequence Generation Mode */}
      <div className="flex flex-col gap-2">
        <label htmlFor="sequenceMode" className="flex items-center text-xs font-bold uppercase text-slate-500">
          <span>Sequence Mode</span>
          <InfoTooltip text="Choose between unbounded (infinite stream starting from start index) and bounded (generates numbers from start up to stop index)." />
        </label>
        <select
          id="sequenceMode"
          name="sequenceMode"
          value={sequenceMode}
          onChange={handleChange}
          className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
        >
          <option value="unbounded">Unbounded (Infinite Stream)</option>
          <option value="bounded">Bounded (Fixed Range)</option>
        </select>
        <span className="text-xs text-slate-500">
          {sequenceMode === 'bounded'
            ? 'Generates numbers from start (inclusive) up to stop (exclusive).'
            : 'Generates an infinite stream of increasing numbers starting from the start index.'}
        </span>
      </div>

      {/* Start Value */}
      <div className="flex flex-col gap-2">
        <label htmlFor="start" className="flex items-center text-xs font-bold uppercase text-slate-500">
          <span>Start Index (.from / start)</span>
          <InfoTooltip text="The starting sequence number (inclusive) generated by GenerateSequence.from(start) or start=0." />
        </label>
        <input
          id="start"
          type="number"
          name="start"
          value={start}
          onChange={handleChange}
          placeholder="0"
          className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
        />
        <span className="text-xs text-slate-500">Starting index of the sequence (inclusive).</span>
      </div>

      {/* Stop Value (only if Bounded) */}
      {sequenceMode === 'bounded' && (
        <div className="flex flex-col gap-2">
          <label htmlFor="stop" className="flex items-center text-xs font-bold uppercase text-slate-500">
            <span>Stop Index (.to / stop)</span>
            <InfoTooltip text="The terminating sequence number (exclusive) generated by GenerateSequence.to(stop) or stop=10 in bounded mode." />
          </label>
          <input
            id="stop"
            type="number"
            name="stop"
            value={stop}
            onChange={handleChange}
            placeholder="10"
            className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
          />
          <span className="text-xs text-slate-500">Ending index of the sequence (exclusive).</span>
        </div>
      )}

      {/* Rate Limiting Toggle & Configuration */}
      <div className="flex flex-col gap-3 p-3 bg-slate-800/40 rounded border border-slate-700/50">
        <label htmlFor="withRateLimit" className="flex items-center gap-2 cursor-pointer">
          <input
            id="withRateLimit"
            type="checkbox"
            name="withRateLimit"
            checked={withRateLimit}
            onChange={handleChange}
            className="w-4 h-4 rounded border-slate-700 text-blue-600 focus:ring-0 focus:ring-offset-0 bg-[#252836]"
          />
          <span className="text-sm font-medium text-slate-300">Rate Limiting (.withRate)</span>
          <InfoTooltip text="Rate limit element emissions using GenerateSequence.withRate(elementsPerPeriod, period) in Java or elements_per_period and period (ms) in Python." />
        </label>

        {withRateLimit && (
          <div className="grid grid-cols-2 gap-3 mt-1">
            <div className="flex flex-col gap-1">
              <label htmlFor="elementsPerPeriod" className="flex items-center text-xs font-semibold text-slate-400">
                <span>Elements / Period</span>
                <InfoTooltip text="Number of elements to output per interval period." />
              </label>
              <input
                id="elementsPerPeriod"
                type="number"
                name="elementsPerPeriod"
                min="1"
                value={elementsPerPeriod}
                onChange={handleChange}
                placeholder="1"
                className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
              />
            </div>
            <div className="flex flex-col gap-1">
              <label htmlFor="periodSeconds" className="flex items-center text-xs font-semibold text-slate-400">
                <span>Period (Seconds)</span>
                <InfoTooltip text="Interval duration between emission cycles in seconds." />
              </label>
              <input
                id="periodSeconds"
                type="number"
                name="periodSeconds"
                min="0.1"
                step="any"
                value={periodSeconds}
                onChange={handleChange}
                placeholder="1"
                className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
              />
            </div>
          </div>
        )}
      </div>

      {/* Max Read Time (Optional) */}
      <div className="flex flex-col gap-2">
        <label htmlFor="maxReadTimeSeconds" className="flex items-center text-xs font-bold uppercase text-slate-500">
          <span>Max Read Time (Seconds, Optional)</span>
          <InfoTooltip text="Limits the maximum duration for reading sequence elements via withMaxReadTime(Duration)." />
        </label>
        <input
          id="maxReadTimeSeconds"
          type="number"
          name="maxReadTimeSeconds"
          min="1"
          value={maxReadTimeSeconds}
          onChange={handleChange}
          placeholder="Leave empty for indefinite"
          className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500"
        />
        <span className="text-xs text-slate-500">
          Limits the maximum duration for reading sequence elements.
        </span>
      </div>

      {/* Code Generation Instructions */}
      <div className="flex flex-col gap-2">
        <label htmlFor="system_instructions" className="flex items-center text-xs font-bold uppercase text-slate-500">
          <span>Code Generation Instructions</span>
          <InfoTooltip text="Optional custom guidance injected into the LLM code generation prompt for this transform." />
        </label>
        <textarea
          id="system_instructions"
          name="system_instructions"
          value={systemInstructions}
          onChange={handleChange}
          placeholder="Enter custom instructions for code generation..."
          rows={3}
          className="bg-[#252836] text-white p-2 rounded border border-slate-700 text-sm focus:outline-none focus:border-blue-500 resize-y"
        />
      </div>
    </div>
  );
};
